create or replace function public.place_order(
    p_items jsonb,
    p_coupon text default null,
    p_profile_name text default null,
    p_profile_email text default null,
    p_client_token uuid default gen_random_uuid()
)
returns table(order_id bigint, order_number text, subtotal_cents integer, discount_cents integer, total_cents integer)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_customer_id bigint;
    v_order_id bigint;
    v_order_number text;
    v_subtotal integer := 0;
    v_discount integer := 0;
    v_item jsonb;
    v_product public.products%rowtype;
    v_quantity integer;
    v_coupon public.coupons%rowtype;
begin
    if p_items is null or jsonb_array_length(p_items) = 0 then
        raise exception 'O carrinho está vazio.';
    end if;

    if coalesce(btrim(p_profile_email), '') <> '' then
        insert into public.customers (name, email)
        values (
            coalesce(nullif(btrim(p_profile_name), ''), 'Cliente Chiquinho'),
            lower(btrim(p_profile_email))
        )
        on conflict (email) do update set name = excluded.name
        returning id into v_customer_id;
    end if;

    for v_item in select * from jsonb_array_elements(p_items)
    loop
        v_quantity := greatest(coalesce((v_item->>'quantity')::integer, 0), 0);
        if v_quantity = 0 then
            raise exception 'Quantidade inválida.';
        end if;

        select * into v_product
        from public.products
        where id = v_item->>'product_id' and is_active;

        if not found then
            raise exception 'Produto inválido: %', v_item->>'product_id';
        end if;

        v_subtotal := v_subtotal + v_product.price_cents * v_quantity;
    end loop;

    if coalesce(p_coupon, '') <> '' then
        select * into v_coupon
        from public.coupons
        where code = upper(p_coupon) and is_active
          and (expires_at is null or expires_at > now());

        if found then
            if v_subtotal < v_coupon.minimum_order_cents then
                raise exception 'Esse cupom vale em pedidos a partir de R$ %.',
                    trim(to_char(v_coupon.minimum_order_cents / 100.0, 'FM999990.00'));
            end if;

            if v_coupon.discount_type = 'percentage' then
                v_discount := round(v_subtotal * v_coupon.discount_value / 100.0);
            else
                v_discount := least(v_subtotal, v_coupon.discount_value);
            end if;
        end if;
    end if;

    v_order_number := 'CHI-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));

    insert into public.orders (
        order_number, customer_id, client_token, coupon_code,
        subtotal_cents, discount_cents, total_cents
    )
    values (
        v_order_number, v_customer_id, p_client_token,
        nullif(upper(coalesce(p_coupon, '')), ''),
        v_subtotal, v_discount, v_subtotal - v_discount
    )
    returning id into v_order_id;

    for v_item in select * from jsonb_array_elements(p_items)
    loop
        v_quantity := (v_item->>'quantity')::integer;
        select * into v_product
        from public.products
        where id = v_item->>'product_id';

        insert into public.order_items (
            order_id, product_id, product_name, unit_price_cents, quantity
        )
        values (
            v_order_id, v_product.id, v_product.name,
            v_product.price_cents, v_quantity
        );
    end loop;

    if v_customer_id is not null then
        insert into public.customer_points (customer_id, balance)
        values (v_customer_id, 0)
        on conflict (customer_id) do nothing;
    end if;

    return query
    select v_order_id, v_order_number, v_subtotal, v_discount, v_subtotal - v_discount;
end;
$$;

revoke all on function public.place_order(jsonb, text, text, text, uuid) from public;
grant execute on function public.place_order(jsonb, text, text, text, uuid) to anon, authenticated;
