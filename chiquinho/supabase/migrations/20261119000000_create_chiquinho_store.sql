create table if not exists public.products (
    id text primary key,
    name text not null,
    description text not null default '',
    price_cents integer not null check (price_cents >= 0),
    old_price_cents integer check (old_price_cents is null or old_price_cents >= price_cents),
    image_path text not null,
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.customers (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(btrim(name)) between 2 and 60),
    email text not null,
    created_at timestamptz not null default now(),
    unique (email)
);

create table if not exists public.coupons (
    code text primary key,
    discount_type text not null check (discount_type in ('percentage', 'fixed', 'points')),
    discount_value integer not null check (discount_value > 0),
    minimum_order_cents integer not null default 0 check (minimum_order_cents >= 0),
    requires_points integer not null default 0,
    is_active boolean not null default true,
    expires_at timestamptz
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    order_number text not null unique,
    customer_id bigint references public.customers(id) on delete set null,
    client_token uuid not null,
    status text not null default 'pending'
        check (status in ('pending', 'confirmed', 'preparing', 'completed', 'cancelled')),
    coupon_code text references public.coupons(code) on delete set null,
    subtotal_cents integer not null check (subtotal_cents >= 0),
    discount_cents integer not null default 0 check (discount_cents >= 0),
    total_cents integer not null check (total_cents >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    order_id bigint not null references public.orders(id) on delete cascade,
    product_id text references public.products(id) on delete set null,
    product_name text not null,
    unit_price_cents integer not null check (unit_price_cents >= 0),
    quantity integer not null check (quantity > 0),
    line_total_cents integer not null generated always as (unit_price_cents * quantity) stored
);

create table if not exists public.customer_points (
    customer_id bigint primary key references public.customers(id) on delete cascade,
    balance integer not null default 0 check (balance >= 0),
    updated_at timestamptz not null default now()
);

